/*
 * Übung zu den Escape-Sequenzen "\n" u. "\t"
 */

public class Tabelle {

	public static void main(String[] args) {
			// Tabellenüberschrift
		System.out.println("\nDies ist eine Tabelle:\n");
		
			// Spaltenüberschrirt
		System.out.println("\t\tSpalte 1 \tSpalte 2 \tSpalte 3\n");
		
			// Inhalt der Tabelle
		System.out.println("Zeile 1: \t3 \t\t5500 \t\t4");
		System.out.println("Zeile 2: \t987 \t\t85 \t\t3");
		System.out.println("Zeile 3: \t9999 \t\t58 \t\t576");
	}
}
